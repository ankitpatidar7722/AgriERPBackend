    CONSTRAINT "UQ_PurchaseReturns_Number" UNIQUE ("ReturnNumber"),
    CONSTRAINT "CK_PurchaseReturns_Status" CHECK ("Status" IN ('Cancelled','Posted','Draft'))
);

CREATE INDEX "IX_PurchaseReturns_Date"
    ON "PurchaseReturns" ("ReturnDate") INCLUDE ("SupplierId", "TaxableAmount", "GrandTotal", "Status");
CREATE INDEX "IX_PurchaseReturns_Supplier_Date"
    ON "PurchaseReturns" ("SupplierId", "ReturnDate") INCLUDE ("ReturnNumber", "GrandTotal", "Status");

CREATE TABLE "PurchaseReturnDetails"
